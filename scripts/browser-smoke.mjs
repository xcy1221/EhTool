  await native.fill('language:english$');
  await page.getByRole('button', { name: 'Apply Filter', exact: true }).click();
  assert.match(await page.locator('#submitted').textContent(), /advsearch=1/);
  assert.match(await page.locator('#submitted').textContent(), /f_srdd=4/);
  await context.close();
  context = await chromium.launchPersistentContext(profile, options);
  page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4174');
  const reopened = page.locator('#eh-search-tool');
  assert.equal(await reopened.locator('h2').textContent(), 'eh工具');
